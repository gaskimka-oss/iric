_CLEAN = re.compile(r"[^а-яёa-z0-9@$]+")
_REPEAT = re.compile(r"(.)\1{2,}")


# полная латиница → кириллица (для слов вида DEBIL, tupoy, loh)
TRANSLIT = {
    "sch": "щ", "sh": "ш", "ch": "ч", "zh": "ж", "yu": "ю", "ya": "я",
    "yo": "е", "ts": "ц", "kh": "х", "ee": "и", "oo": "у",
    "a": "а", "b": "б", "c": "к", "d": "д", "e": "е", "f": "ф", "g": "г",
    "h": "х", "i": "и", "j": "й", "k": "к", "l": "л", "m": "м", "n": "н",
    "o": "о", "p": "п", "q": "к", "r": "р", "s": "с", "t": "т", "u": "у",
    "v": "в", "w": "в", "x": "х", "y": "ы", "z": "з",
}


def _translit(t: str) -> str:
    """Транслитерация латиницы в кириллицу."""
    out, i = [], 0
    while i < len(t):
        for ln in (3, 2, 1):
            chunk = t[i:i + ln]
            if chunk in TRANSLIT:
                out.append(TRANSLIT[chunk])
                i += ln
                break
        else:
            out.append(t[i])
            i += 1
    return "".join(out)


def normalize(text: str) -> str:
    """«п.р.и.в.е.т», «пppивеeт», «п р и в е т» → «привет»."""
    t = (text or "").lower().replace("ё", "е")
    t = t.translate(LEET)
    t = _CLEAN.sub("", t)
    t = _REPEAT.sub(r"\1", t)
    return t


def normalize_all(text: str) -> list[str]:
    """Даёт несколько вариантов написания для проверки."""
    base = normalize(text)
    variants = [base]
    # чистая латиница -> транслит
    low = (text or "").lower()
    if re.search(r"[a-z]", low):
        lat = _CLEAN.sub("", _REPEAT.sub(r"\1", low.replace("ё", "е")))
        tr = _translit(lat)
        if tr != base:
            variants.append(tr)
        # вариант с y→й/и (huy → хуй, muday → мудай)
        tr2 = _translit(lat.replace("y", "j"))
        if tr2 not in variants:
            variants.append(tr2)
        tr3 = _translit(lat.replace("y", "i"))
        if tr3 not in variants:
            variants.append(tr3)
    return variants


