def _only_interjection(raw: str) -> bool:
    """Сообщение — просто эмоция без обращения («бля», «ну пиздец»)."""
    low = raw.lower().replace("ё", "е")
    words = [w for w in re.split(r"[^а-яa-z]+", low) if w]
    if not words or len(words) > 7:
        return False
    # все слова — междометия или мусорные частицы
    filler = {"как","же","так","это","всё","все","что","вообще","опять",
              "уже","прям","совсем","блин","да","нет","и","а","но","ну"}
    for w in words:
        if w in filler:
            continue
        if any(w.startswith(normalize(i)) for i in _INTERJECTION):
            continue
        return False
    return True


# мат о себе или о ситуации, а не о человеке
_SELF = ["я ", "мне ", "меня ", "мной ", "мой ", "моя ", "мое ", "мои ",
         "нам ", "нас ", "мы ", "себя ", "устал", "задолбал", "achieved"]
_ABOUT_THING = ["эту", "этот", "это", "эта", "работу", "работа", "погод",
                "ситуац", "жизнь", "день", "неделю", "игру", "комп",
                "интернет", "телефон", "всё это", "все это"]

# оценка ситуации: «хуево получилось», «пиздато вышло»
_EVAL_ADV = ["хуев", "хуёв", "пиздат", "заебис", "охуенн", "ахуенн",
             "херов", "погано", "хреново"]
_EVAL_VERB = ["получил", "вышло", "выходит", "сделал", "здела", "прошло",
              "работает", "получается", "звучит", "смотрится", "идет", "идёт"]


def _about_self_or_thing(raw: str) -> bool:
    """«заебался», «ебать я устал», «нахуй эту работу» — не про человека."""
    low = " " + raw.lower().replace("ё", "е") + " "
    # явное указание на себя
    for w in _SELF:
        if f" {w}" in low:
            return True
    # мат в адрес предмета/ситуации
    for w in _ABOUT_THING:
        if w in low:
            return True
    # возвратные глаголы: заебался, задолбался, охренел
    import re as _re
    if _re.search(r"\b\w*(ался|алась|ались)\b", low):
        return True
    # оценка ситуации: «хуево получилось»
    if any(a in low for a in _EVAL_ADV) and any(v in low for v in _EVAL_VERB):
        return True
    # одиночное оценочное наречие без адресата: «хуево», «пиздато»
    words = [w for w in _re.split(r"[^а-яa-z]+", low) if w]
    if len(words) <= 2 and words and any(
            words[0].startswith(a) for a in _EVAL_ADV):
        return True
    return False


def _is_addressed(raw: str, has_reply: bool = False, has_mention: bool = False) -> bool:
    """Направлено ли сообщение на конкретного человека."""
    # чистая эмоция — даже реплаем это не оскорбление
    if _only_interjection(raw):
        return False
    if has_reply or has_mention:
        return True
    low = " " + raw.lower().replace("ё", "е") + " "
    for w in _ADDRESS:
        if f" {w} " in low or low.startswith(w + " "):
            return True
    return "@" in raw


def local_check(text: str) -> tuple[int, str]:
    """-> (уровень 0..3, причина).

    0 — чисто · 1 — грубость · 2 — оскорбление · 3 — мат/угроза
    """
    raw = (text or "").strip()
    if not raw or len(raw) < 2:
        return 0, ""

    low = raw.lower().replace("ё", "е")
    for w in _WHITELIST:
        if w in low:
            return 0, ""

    norm = normalize_all(raw)
    if not any(norm):
        return 0, ""

    # отдельные слова — для проверки коротких корней
    words = [normalize(w) for w in re.split(r"[\s,.!?;:()\[\]\"\'-]+", low) if w]
    words = [w for w in words if w]

    hit = _has_root(norm, _THREAT_ROOTS, words)
    if hit:
        return 3, "угроза"

    hit = _has_root(norm, _OBSCENE_ROOTS, words)
    if hit:
        return 3, "нецензурная брань"

    hit = _has_root(norm, _INSULT_ROOTS, words)
    if hit:
        return 2, "оскорбление"

    # КАПС-крик длиннее 15 символов
    letters = [c for c in raw if c.isalpha()]
    if len(letters) >= 15:
        upper = sum(1 for c in letters if c.isupper())
        if upper / len(letters) > 0.8:
            return 1, "капс"

    return 0, ""


# ── ИИ-слой (опционально) ─────────────────────────────────────────────
AI_KEY = os.getenv("AI_API_KEY", "").strip()
AI_URL = os.getenv("AI_API_URL", "https://api.openai.com/v1/chat/completions").strip()
AI_MODEL = os.getenv("AI_MODEL", "gpt-4o-mini").strip()

SYSTEM_PROMPT = (
    "Ты модератор русскоязычного чата. Оцени сообщение по шкале:\n"
    "0 — нормальное общение, шутки между друзьями, спор без перехода на личности\n"
    "1 — грубость, хамство, капс\n"
    "2 — прямое оскорбление участника\n"
    "3 — мат в адрес человека, угрозы, травля\n\n"
    "Отвечай СТРОГО в формате JSON: {\"level\": 0-3, \"reason\": \"кратко\"}\n"
    "Дружеские подколы и мат «в воздух» без адресата — это 0 или 1."
)


def ai_available() -> bool:
    return bool(AI_KEY)


def ai_check(text: str, timeout: int = 8) -> tuple[int, str] | None:
    """Запрос к ИИ. None — если ИИ недоступен или ошибка."""
    if not AI_KEY:
        return None
    body = json.dumps({
        "model": AI_MODEL,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": text[:800]},
        ],
        "temperature": 0,
        "max_tokens": 60,
    }).encode()
    req = urllib.request.Request(
        AI_URL, body,
        {"Content-Type": "application/json",
         "Authorization": f"Bearer {AI_KEY}"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            data = json.load(r)
        content = data["choices"][0]["message"]["content"].strip()
        content = re.sub(r"^```(?:json)?|```$", "", content).strip()
        parsed = json.loads(content)
        lvl = int(parsed.get("level", 0))
        return max(0, min(lvl, 3)), str(parsed.get("reason", ""))[:80]
    except Exception:
        return None


async def check(text: str, use_ai: bool = True, addressed: bool = False,
                punish_soft_mat: bool = False,
                context: str = "") -> tuple[int, str, str]:
    """-> (уровень, причина, источник).

    addressed — сообщение адресовано человеку (реплай/@ник/«ты…»).
    punish_soft_mat — наказывать мат-междометия без адресата.
    context — переписка вокруг сообщения: с ней ИИ отличает
              дружеский подкол от настоящего оскорбления.
    """
    lvl, reason = local_check(text)

    # мат «в воздух» без адресата — не наказываем (если не включено строго)
    if lvl == 3 and reason == "нецензурная брань" and not punish_soft_mat:
        if _only_interjection(text) or _about_self_or_thing(text):
            return 0, "", "словарь"
        if not (addressed or _is_addressed(text)):
            return 0, "", "словарь"

    # ИИ смотрит на переписку и может как повысить оценку,
    # так и ОТМЕНИТЬ ложное срабатывание словаря.
    #
    # Экономия запросов: дёргаем ИИ не на каждое сообщение, а только
    # когда есть о чём думать — словарь что-то заметил, либо фраза
    # адресная. Так бесплатных лимитов хватает надолго.
    worth_asking = (lvl >= 1) or addressed or _is_addressed(text)
    if use_ai and worth_asking and len(text.strip()) >= 8:
        try:
            import core_ai as _ai
            if _ai.available():
                r = await _ai.watch_message(text, context)
                if r:
                    if r["level"] > lvl:
                        return r["level"], r["reason"] or "нарушение", "ИИ"
                    if r["level"] < lvl:
                        # ИИ увидел контекст: дружеский подкол, цитата, шутка
                        return (r["level"],
                                r["reason"] or "по контексту не нарушение",
                                "ИИ")
                    return lvl, reason, "словарь+ИИ"
        except Exception:
            pass
        # запасной путь — старый прямой запрос
        if AI_KEY and lvl < 2:
            import asyncio
            res = await asyncio.to_thread(ai_check, text)
            if res and res[0] > lvl:
                return res[0], res[1] or "нарушение", "ИИ"

    return lvl, reason, "словарь"
