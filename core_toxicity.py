# корни короче 5 букв слишком «жадные» — ищем их как начало слова
_SHORT = 4


def _has_root(variants: list[str], roots: list[str],
              words: list[str] | None = None) -> str | None:
    for r in roots:
        rn = normalize(r)
        if not rn:
            continue
        if len(rn) <= _SHORT and words:
            # короткий корень: только начало отдельного слова
            for w in words:
                if w.startswith(rn):
                    return r
            continue
        for v in variants:
            if rn in v:
                return r
    return None


